interface PixelHairProps {
  style: HairStyle;
  color?: HairColor;
  size?: number;
  className?: string;
}

/**
 * Inline SVG pixel hair layer.
 * Warna dinamis via prop, rendered as rects on 24x24 grid.
 * Stack di atas layer-body dengan absolute positioning.
 */
export function PixelHair({
  style,
  color = "hitam",
  size = 96,
  className = "",
}: PixelHairProps) {
  const hex = HAIR_COLORS[color] || HAIR_COLORS.hitam;
  const pixels = HAIR_PIXELS[style] || [];

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      style={{ imageRendering: "pixelated" }}
    >
      <g id="layer-hair" data-style={style}>
        {pixels.map(([x, y], i) => (
          <rect key={i} x={x} y={y} width={1} height={1} fill={hex} />
        ))}
      </g>
    </svg>
  );
}
